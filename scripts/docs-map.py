#!/usr/bin/env python3
"""docs-map.py — docs/ 트리 스냅샷을 docs/generated/doc-map.md 로 출력."""
from __future__ import annotations
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"


def walk(prefix: Path, depth: int = 0, out: list[str] | None = None) -> list[str]:
    if out is None:
        out = []
    for p in sorted(prefix.iterdir()):
        if p.name.startswith("."):
            continue
        indent = "  " * depth
        if p.is_dir():
            out.append(f"{indent}- **{p.name}/**")
            walk(p, depth + 1, out)
        else:
            out.append(f"{indent}- {p.name}")
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", default="docs/generated/doc-map.md")
    args = ap.parse_args()
    lines = ["<!-- GENERATED by scripts/docs-map.py — do not edit by hand -->", "# docs/ map", ""]
    if DOCS.exists():
        lines.extend(walk(DOCS))
    target = ROOT / args.write
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)} ({len(lines)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
